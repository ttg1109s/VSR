import { readFileSync, writeFileSync } from 'node:fs';

const sourcePath = new URL('../scenario.schema.json', import.meta.url);
const outputPath = new URL('../engine/scenario/ScenarioSchema.js', import.meta.url);
const schema = JSON.parse(readFileSync(sourcePath, 'utf8'));

if (!schema || schema.$schema !== 'http://json-schema.org/draft-07/schema#') {
  throw new Error('scenario.schema.json must be a valid Draft-07 JSON Schema.');
}

const output = `// Generated by tools/generate-scenario-schema.js from /scenario.schema.json. Do not edit manually.\nexport const scenarioSchema = ${JSON.stringify(schema)};\n`;
writeFileSync(outputPath, output);
